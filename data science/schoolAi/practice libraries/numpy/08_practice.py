import numpy as np
np.random.seed(42)

marks = np.random.randint(25,100,size=(100,5))
print(np.mean(marks))
print(np.median(marks))
print(np.std(marks))
print(np.max(marks))
print(np.min(marks))
student_total = marks.sum(axis=1)
student_mean = marks.mean(axis=1)
print(np.argmax(marks))
print(np.argmin(marks))
print(np.sum(marks>np.mean(marks)))
print(student_total)
print(student_mean)
print(np.argmax(student_total))
print(np.argmin(student_total))
print(np.sum(np.mean(marks)<student_mean))
